"""提示词工程核心。

设计思路：
1. 角色设定：特级教师 + 高考阅卷组组长，锚定专业语域。
2. 评分标准对齐：把新高考“基础等级 + 发展等级”写进提示词。
3. 分阶段生成：先审题立纲，再成文，降低跑题与结构松散风险。
4. 显式约束：字数、结构、素材、语言、禁忌、输出格式。
5. 自我检查：要求模型在内部按评分标准自检后再输出，不暴露思维链。
6. 风格锚点：给出高分范文片段作为风格参照，而非照抄模板。
"""

GENRE_HINTS = {
    "议论文": "写成规范的考场议论文：中心论点鲜明，3 个分论点层层递进，兼有辩证段与结尾升华。",
    "记叙文": "写成记叙文：以具体事件和细节推进，以小见大，结尾点题升华，避免流水账。",
    "散文": "写成议论性散文：以意象贯穿，情理交融，形散神聚，但中心观点必须清晰。",
    "书信": "写成书信体：格式规范（称呼、正文、祝语、署名、日期），说理真挚，对象感明确。",
}

STYLE_HINTS = {
    "满分冲刺": "立意求深、结构求稳、材料求新、语言求美，冲击 55 分以上。",
    "稳健高分": "审题绝对准确，结构清晰，论据充分，语言通顺有文采，确保 50 分以上。",
    "思辨深刻": "强化辩证分析与因果推演，写出层次感与思想张力，避免非黑即白。",
    "文采斐然": "在切题前提下强化修辞、句式与引用，语言有画面感和节奏感，但不堆砌辞藻。",
}

SYSTEM_PROMPT = """你是一位深耕高中语文教学与高考阅卷二十余年的特级教师，长期担任高考作文阅卷组组长，熟悉《普通高中语文课程标准》和新高考作文评分标准。

【评分标准内化】
- 基础等级（40 分）：内容（20 分）要求切题、中心突出、材料充实、思想健康；表达（20 分）要求结构严谨、语言流畅、文体规范。
- 发展等级（20 分）：深刻、丰富、有文采、有创意。鼓励透过现象看本质、揭示因果、观点具有启发性。

【写作铁律】
1. 审题第一：准确提炼题目或材料的核心矛盾与价值指向，立意不偏、不泛、不套作。
2. 结构清晰：议论文采用“引—议—联—结”或“总—分—总”，分论点之间有逻辑递进，不并列堆砌。
3. 材料鲜活：古今中外结合，事实准确，优先使用具体、有细节、少被滥用的素材；名言引用必须准确。
4. 语言有文采：长短句结合，适当运用排比、比喻、引用、对比，但拒绝辞藻堆砌和空喊口号。
5. 文体纯粹：议论文像议论文，记叙文像记叙文，不写成“四不像”。
6. 标题出彩：8—14 字，含蓄凝练，能统摄全文，避免“论××”“××的启示”这类平庸标题。
7. 严禁：套作宿构、网络烂梗、假大空口号、无逻辑的材料罗列、模板化开头。

【输出纪律】
- 只输出用户要求的内容，不解释写作思路，不输出 Markdown 代码块围栏。
- 作文正文使用自然分段，标题单独一行。
- 不要把内部自我检查过程写出来。"""


def _profile(
    title: str,
    material: str,
    genre: str,
    word_count: int,
    style: str,
    extra: str,
) -> str:
    genre_hint = GENRE_HINTS.get(genre, GENRE_HINTS["议论文"])
    style_hint = STYLE_HINTS.get(style, STYLE_HINTS["满分冲刺"])
    material_block = material.strip() or "（无额外材料，请依据题目本身审题立意）"
    extra_block = extra.strip() or "（无）"
    return f"""【作文题目】
{title.strip()}

【题目材料 / 写作要求】
{material_block}

【文体】
{genre}。{genre_hint}

【目标字数】
约 {word_count} 字（允许上下浮动 10%）。

【风格目标】
{style}。{style_hint}

【附加要求】
{extra_block}"""


def build_outline_messages(
    title: str,
    material: str,
    genre: str,
    word_count: int,
    style: str,
    extra: str,
) -> list[dict]:
    user = f"""{_profile(title, material, genre, word_count, style, extra)}

请先完成审题与构思，输出一份可以直接指导考场写作的详细大纲。严格按以下格式输出，不要写正文：

一、审题立意
- 材料关键词：
- 核心矛盾 / 价值指向：
- 我的立意：
- 容易跑偏的角度及规避：

二、中心论点
- 用一句 20—35 字的话概括：

三、标题备选
1. （8—14 字，含蓄有文采）
2. （8—14 字，观点鲜明）
3. （8—14 字，意象化）

四、结构提纲
- 开头（约 100 字）：如何引题、亮明论点
- 分论点一：
- 分论点二：
- 分论点三：
- 辩证 / 反方段：
- 结尾（约 100 字）：如何升华

五、素材与名言
- 事实论据 3 个（注明人物 / 事件 + 可切入的角度）
- 名言 2 句（注明出处，确保准确）

六、写作提醒
- 本文最需要避免的一个问题：
- 最容易出彩的一个地方：

注意：大纲要具体到可以直接落笔，不要空话。"""
    return [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": user},
    ]


FEW_SHOT_STYLE = """【风格锚点（只学其法与气韵，严禁照抄句子）】
围棋中，弈者往往求胜心切，不知“以正合”的兵家正道，莫不想着“以奇胜”的诡道，希冀一招致胜，毕其功于一役。殊不知，妙手不可偶得，本手游刃有余，妙手才可练就。
庄子笔下的庖丁，其“以神遇而不以目视”的绝技背后，是十九年、“所解数千牛”的扎实基本功；达·芬奇惊世名画《蒙娜丽莎》的微笑，其神韵或许从画蛋练功中绘就；苏轼的意到笔随，常有神来之笔，其才情在“立志读尽人间书”的苦读中酝酿。
守拙以守正，苦练基本功，练就本手；创新兼创意，熟能生巧，才能妙手偶得。"""


def build_essay_messages(
    title: str,
    material: str,
    genre: str,
    word_count: int,
    style: str,
    extra: str,
    outline: str,
) -> list[dict]:
    user = f"""{_profile(title, material, genre, word_count, style, extra)}

【已确认的写作大纲】
{outline.strip()}

{FEW_SHOT_STYLE}

请严格依据大纲，写一篇可以直接誊写到答题卡上的高考{genre}。要求：
1. 标题单独一行，不加“题目：”等字样。
2. 正文约 {word_count} 字，分段自然，议论文 5—7 段。
3. 开头 3 句内进入主题，结尾要有余味，不喊空洞口号。
4. 分论点句式有变化，材料与观点之间要有分析，不能“观点 + 例子”简单拼接。
5. 至少有一处辩证思考或对反面观点的回应，体现思维深度。
6. 动笔前在心里按评分标准自检：是否切题？结构是否清晰？材料是否准确？语言是否有文采？
7. 只输出作文本身，不要输出大纲、说明、字数统计或 Markdown 围栏。"""
    return [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": user},
    ]


def build_direct_messages(
    title: str,
    material: str,
    genre: str,
    word_count: int,
    style: str,
    extra: str,
) -> list[dict]:
    """快速模式：跳过显式大纲，一次成文。"""
    user = f"""{_profile(title, material, genre, word_count, style, extra)}

{FEW_SHOT_STYLE}

请直接写一篇可以直接誊写到答题卡上的高考{genre}。先在内部完成审题、立意、结构与素材自检，再动笔；不要输出思考过程。

要求：
1. 标题单独一行，8—14 字，有文采。
2. 正文约 {word_count} 字，结构完整，层次清晰。
3. 材料准确、具体，避免烂大街素材；名言引用必须准确。
4. 至少有一处辩证思考。
5. 只输出作文本身，不要任何解释或 Markdown 围栏。"""
    return [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": user},
    ]


